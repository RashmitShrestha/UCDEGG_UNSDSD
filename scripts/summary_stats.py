"""Regenerate summary_stats.md: the headline numbers behind analysis.md.

analysis.md is hand-written prose; this file is the machine-made source for
its tables, so after an update compare the two and copy over what changed.
"""
import sys

import pandas as pd

from common import ROOT

KV_BANDS = [(500, "500–765 kV"), (345, "345 kV"), (230, "230 kV"), (0, "115–161 kV")]


def md(df: pd.DataFrame) -> str:
    def cell(v):
        if pd.isna(v):
            return "—"
        if isinstance(v, float):
            return f"{v:,.0f}" if abs(v) >= 100 else f"{v:.1f}"
        return str(v)
    rows = ["| " + " | ".join(df.columns) + " |", "|" + "|".join("---" for _ in df.columns) + "|"]
    rows += ["| " + " | ".join(cell(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(rows)


def n_mw(df, col):
    return f"{len(df)} plants, {df[col].sum():,.0f} MW"


def main() -> None:
    release = sys.argv[1] if len(sys.argv) > 1 else "latest release"
    ret = pd.read_csv(ROOT / "retired_plants_truck_proximity.csv")
    op = pd.read_csv(ROOT / "coal_plants_truck_proximity.csv")
    tx = pd.read_csv(ROOT / "retired_plants_transmission.csv")[["Plant ID", "max_kv"]]
    ret = ret.merge(tx, on="Plant ID", how="left")
    idle = pd.read_csv(ROOT / "idle_fossil_plants.csv")
    units = pd.read_csv(ROOT / "idle_fossil_units.csv")
    big = idle[idle.idle_fossil_mw >= 20]

    out = [f"# Summary statistics (auto-generated from EIA-860M {release})", "",
           "Regenerated by `python update.py`. Do not edit by hand.", "",
           "## Retired coal plants", "",
           f"- Fully retired since {ret.retired_yr.min()}: **{n_mw(ret, 'coal_mw')}**",
           f"- Median size {ret.coal_mw.median():,.0f} MW (mean {ret.coal_mw.mean():,.0f})",
           f"- 230 kV+ line within 1 mile: {n_mw(ret[ret.max_kv >= 230], 'coal_mw')}",
           f"- Within 5 mi of a 1,000+ trucks/day route: {n_mw(ret[ret.mi_to_freight_net <= 5], 'coal_mw')}",
           f"- Shortlist (≤5 mi, ≥230 kV, ≥2,500 trucks/day ≤10 mi): "
           f"{n_mw(ret[(ret.mi_to_freight_net <= 5) & (ret.max_kv >= 230) & (ret.max_trucks_day_10mi >= 2500)], 'coal_mw')}",
           f"- Operating coal plants with units retiring by 2030: "
           f"{len(op[op.status == 'Retiring by 2030'])} plants, {op.loc[op.status == 'Retiring by 2030', 'mw_retiring'].sum():,.0f} MW", "",
           "### By retirement year", "",
           md(ret.astype({"retired_yr": str}).groupby("retired_yr").agg(Plants=("coal_mw", "size"), MW=("coal_mw", "sum"))
              .reset_index().rename(columns={"retired_yr": "Year"})), "",
           "### Highest voltage within 1 mile", ""]
    band = ret.max_kv.map(lambda k: "None mapped" if pd.isna(k) else next(l for v, l in KV_BANDS if k >= v * 0.95))
    order = [l for _, l in KV_BANDS] + ["None mapped"]
    by_band = (ret.assign(band=band).groupby("band").agg(Plants=("coal_mw", "size"), MW=("coal_mw", "sum"))
               .reindex(order).dropna().reset_index().rename(columns={"band": "Max kV"}))
    by_band["Plants"] = by_band["Plants"].astype(int)
    out += [md(by_band), "",
            "## Idle fossil plants (OS / OA / SB)", "",
            f"- Idle fossil units (any plant): {len(units)} units, {units.mw.sum():,.0f} MW",
            f"- Plants with every fossil unit idle: **{n_mw(idle, 'idle_fossil_mw')}**",
            f"- …of those ≥20 MW: {n_mw(big, 'idle_fossil_mw')}",
            f"- …≥20 MW and ≤5 mi from a 1,000+ trucks/day route: "
            f"{n_mw(big[big.mi_to_freight_net <= 5], 'idle_fossil_mw')}", "",
            md(units.groupby(["fuel_group", "status_code"]).mw.agg(["size", "sum"]).reset_index()
               .rename(columns={"fuel_group": "Fuel", "status_code": "Status", "size": "Units", "sum": "MW"})), "",
            "### Largest fully idle plants", "",
            md(big.head(15)[["plant", "state", "main_fuel", "main_status", "idle_fossil_mw",
                             "mi_to_freight_net", "max_trucks_day_10mi"]].round(1)), ""]
    (ROOT / "summary_stats.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote summary_stats.md")


if __name__ == "__main__":
    main()
